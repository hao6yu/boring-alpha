"""How many months until the forward book could say anything, and whether money can buy that wait down.

Run: .venv/bin/python tools/power_horizon.py [--window both] [--json]

The live book's own report says it needs 23 more monthly seals before a skill claim is supportable. That number invites one
response — *then put more money in* — and this file exists because that response is mostly wrong, in a way that only shows up
once the arithmetic is done at several sizes. Everything an account pays here is proportional to what it holds: a spread in
basis points, an expense ratio per twelve. Double the account and the gap doubles, the noise doubles with it, and the
t-statistic that decides when a difference stops looking like luck does not move at all. **Scale buys dollars, not knowledge.**
What does move it is the flat cost of placing an order, which does not scale, and that is the lever that hurts small accounts
most — the objective's shape.

The claim, written before the run: **the number of months needed to detect the tilt's difference against plain VOO is
invariant to account size when every cost is proportional, and rises sharply as per-order costs replace proportional ones.**
If a per-order commission of a few dollars is enough to make the horizon unreachable, the finding is not that the tilt is bad;
it is that the *account* is too small to express the idea, which is a fact about brokers and not about markets, and the right
answer is a different broker rather than a different model.

Nothing here is hand-derived. The witness path is generated by `paper.shadow_step` itself — the sealed function that produces
the journal's own benchmark entries — and the strategy simulator is differential-tested against it on a one-fund, never-sell
account, so the two accounts in this file are computed by the code the journal trusts. The archive decides the sign: where the
measured difference does not favour the book, there is no horizon to report and none is reported. Round 77's lesson, kept:
an interval on the wrong side of zero is not a finding, it is a refusal.
"""

